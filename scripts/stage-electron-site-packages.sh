#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PYTHON="$ROOT/.electron-python-runtime/bin/python"
LOCK="$ROOT/requirements-electron.lock"
OUT="$ROOT/.electron-site-packages"

if [[ "$(uname -m)" != "arm64" ]]; then
  echo "Electron dependencies are locked for Apple Silicon" >&2
  exit 1
fi
if [[ "$(sw_vers -productVersion | cut -d. -f1)" -lt 14 ]]; then
  echo "macOS 14 or newer is required" >&2
  exit 1
fi
if [[ ! -x "$PYTHON" || ! -f "$LOCK" ]]; then
  echo "stage the Python runtime and generate requirements-electron.lock first" >&2
  exit 1
fi
if ! command -v uv >/dev/null 2>&1; then
  echo "uv is required to stage the Electron dependency set" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
uv venv --python "$PYTHON" "$WORK/venv" >/dev/null
uv pip sync --python "$WORK/venv/bin/python" --require-hashes "$LOCK"

rm -rf "$OUT"
ditto "$WORK/venv/lib/python3.12/site-packages" "$OUT"
find "$OUT" -type d \( -name __pycache__ -o -name tests -o -name test \) -prune -exec rm -rf {} +
find "$OUT" -type f \( -name '*.pyc' -o -name '.DS_Store' \) -delete
rm -rf "$OUT/torch/include" "$OUT/torch/testing" "$OUT/mlx/include"
xattr -cr "$OUT" 2>/dev/null || true

"$PYTHON" "$ROOT/scripts/audit-electron-dependencies.py" "$OUT"
if find "$OUT" -type f -print0 | xargs -0 grep -a -l -F "$HOME" | grep .; then
  echo "private home path remains in Electron dependencies" >&2
  exit 1
fi

PYTHONPATH="$OUT" "$PYTHON" -B - <<'PY'
import cv2, edge_tts, fastapi, httpx, mediapipe, mlx_whisper, numpy, scipy, soundfile, uvicorn
try:
    import kokoro
except ModuleNotFoundError:
    pass
else:
    raise AssertionError("Kokoro must not be redistributed in the Electron app")
print("staged GPL-free Electron dependencies")
PY
